<#
.SYNOPSIS  Run an Apple II program in MAME and print the results.
.EXAMPLE   .\Run-Apple2.ps1 -Project BeginnerTesting -Basic hello.bas -Dump '0300-030F'
.EXAMPLE   .\Run-Apple2.ps1 -Project BeginnerTesting -Asm store.s -Call -WaitPeek '0300=42' -Dump '0300-0303'
#>
[CmdletBinding()]
param(
  [string]$Project = 'BeginnerTesting',
  [string]$Basic,                 # file in src\ (or full path)
  [string]$Bin,                   # file in build\ (or full path)
  [string]$Asm,                   # file in src\ ; assembled to build\<name>.bin
  [string]$LoadAddr = '6000',     # hex
  [switch]$Call,                  # type CALL <LoadAddr> after loading
  [string]$Dump = '',             # e.g. '0300-030F,6000-60FF'
  [int]$BootFrames = 120,
  [int]$Frames = 300,             # frames to run after typing finishes (60 = 1 s)
  [string]$WaitPeek,              # 'addr=value' hex, stop early when matched
  [int]$MaxFrames = 3600,
  [string]$Machine = 'apple2e',
  [switch]$Screenshot,
  [switch]$Headless,
  [switch]$NoScreen
)
$ErrorActionPreference = 'Stop'
$Root    = Split-Path -Parent $PSScriptRoot          # ...\AppleII
$MameDir = Join-Path $Root 'MAME'
$ProjDir = Join-Path $Root "Projects\$Project"
$SrcDir  = Join-Path $ProjDir 'src'
$Build   = Join-Path $ProjDir 'build'
New-Item -ItemType Directory -Force -Path $Build | Out-Null

function Resolve-In($name, $dir) {
  if (-not $name) { return $null }
  if ([IO.Path]::IsPathRooted($name)) { $p = $name } else { $p = Join-Path $dir $name }
  if (-not (Test-Path $p)) { throw "File not found: $p" }
  (Resolve-Path $p).Path
}
function LuaStr($s) { if ($null -eq $s) { 'nil' } else { "'" + ($s -replace '\\','/' -replace "'","\'") + "'" } }

$addr = [Convert]::ToInt32($LoadAddr.TrimStart('$'), 16)

if ($Asm) {
  $src = Resolve-In $Asm $SrcDir
  $cl65 = Join-Path $Root 'Tools\cc65\bin\cl65.exe'
  $out = Join-Path $Build ([IO.Path]::GetFileNameWithoutExtension($src) + '.bin')
  Write-Host "Assembling $src -> $out at `$$('{0:X4}' -f $addr)"
  & $cl65 -t none --start-addr $addr -o $out -l (Join-Path $Build ([IO.Path]::GetFileNameWithoutExtension($src) + '.lst')) $src
  if ($LASTEXITCODE -ne 0) { throw "cl65 failed ($LASTEXITCODE)" }
  $Bin = $out
}
$basicPath = Resolve-In $Basic $SrcDir
$binPath   = Resolve-In $Bin $Build

# dumps -> lua table
$dumps = @()
foreach ($r in ($Dump -split ',' | Where-Object { $_.Trim() })) {
  $a, $b = $r.Trim().TrimStart('$') -split '-'
  if (-not $b) { $b = $a }
  $dumps += "{0x$a,0x$($b.TrimStart('$'))}"
}
$wait = 'nil'
if ($WaitPeek) { $wa, $wv = $WaitPeek -split '='; $wait = "{addr=0x$($wa.Trim().TrimStart('$')),value=0x$($wv.Trim().TrimStart('$'))}" }

$results = Join-Path $Build 'results.txt'
$cfgPath = Join-Path $Build 'runner_cfg.lua'
@"
-- generated by Run-Apple2.ps1 $(Get-Date -Format s)
return {
  basic = $(LuaStr $basicPath),
  bin = $(LuaStr $binPath),
  load_addr = $addr,
  call = $(if ($Call) {'true'} else {'false'}),
  boot_frames = $BootFrames,
  run_frames = $Frames,
  max_frames = $MaxFrames,
  dumps = { $($dumps -join ', ') },
  regs = true,
  screen = $(if ($NoScreen) {'false'} else {'true'}),
  snapshot = $(if ($Screenshot) {'true'} else {'false'}),
  wait_peek = $wait,
  out = $(LuaStr $results),
}
"@ | Set-Content -Encoding ascii $cfgPath

Remove-Item $results -ErrorAction SilentlyContinue
$env:A2RUN_CFG = $cfgPath -replace '\\','/'

$mameArgs = @($Machine, '-sl6', '""', '-skip_gameinfo',
              '-autoboot_script', (Join-Path $PSScriptRoot 'runner.lua'))
if ($Headless) { $mameArgs += @('-video','none','-sound','none','-nothrottle') } else { $mameArgs += '-window' }
if ($Screenshot) { $mameArgs += @('-snapshot_directory', $Build) }

Push-Location $MameDir
try {
  # Build a single argument string so the empty slot value survives as "" on every PowerShell version.
  $argLine = ($mameArgs | ForEach-Object { if ($_ -eq '""') { '""' } elseif ($_ -match '\s') { "`"$_`"" } else { $_ } }) -join ' '
  Write-Host "mame.exe $argLine"
  $p = Start-Process -FilePath '.\mame.exe' -ArgumentList $argLine -NoNewWindow -Wait -PassThru
  Write-Host "MAME exit code: $($p.ExitCode)"
} finally { Pop-Location; Remove-Item Env:A2RUN_CFG -ErrorAction SilentlyContinue }

if (Test-Path $results) { Get-Content $results } else { Write-Warning "No results file at $results" }
