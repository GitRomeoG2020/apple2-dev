#!/usr/bin/env python3
"""The second minute's room patches (src/chapter_art.inc, assembled into the
chapter track, read at boot to $6000). Each patch is a rectangle of native
HGR bytes the engine copies over the canonical room ($8000, and both pages
when it happens in front of G-Bot):
  0 static  the security monitor wall in snow (the guard woke; cable loose)
  1 feeds   the same wall with its six camera feeds back (repaired)
  2 drop1, 3 drop2  wing B: the frozen coffee drop falls into the cup
  4 awake   wing B: the machine awake and scowling, the cup full, steaming
Rectangles: the bounding box of every byte that differs, per room.
Run after gen_security.py and gen_wingb.py. Pillow (via those) is art-only."""
from pathlib import Path
import sys
ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/'tools'))
from gen_concept import row_offset
import gen_security, gen_wingb

def box(base,variants):
    rows=set();cols=set()
    for v in variants:
        for y in range(192):
            for b in range(40):
                if base[row_offset(y)+b]!=v[row_offset(y)+b]:rows.add(y);cols.add(b)
    return min(cols),max(cols)-min(cols)+1,min(rows),max(rows)-min(rows)+1

def cut(img,bx):
    c0,w,r0,h=bx
    return [img[row_offset(r0+r)+c0+c] for r in range(h) for c in range(w)]

def patches():
    sec=gen_security.room();snow=gen_security.room(static=True)
    assert sec==(ROOT/'art/security-room.hgr').read_bytes(),'security art changed: rerun gen_security.py'
    wing=[gen_wingb.room(s) for s in range(4)]
    assert wing[0]==(ROOT/'art/wingb-room.hgr').read_bytes(),'wing B art changed: rerun gen_wingb.py'
    mb=box(sec,[snow]);cb=box(wing[0],wing[1:])
    return [('static',mb,cut(snow,mb)),('feeds',mb,cut(sec,mb)),
            ('drop1',cb,cut(wing[1],cb)),('drop2',cb,cut(wing[2],cb)),('awake',cb,cut(wing[3],cb))]

def main():
    ps=patches()
    lines=['; Generated by tools/gen_chapter.py; do not hand edit.']
    for i,(n,_,_) in enumerate(ps):lines.append('PATCH_%s=%d'%(n.upper(),i))
    for key,k in (('patcol',0),('patw',1),('patrow',2),('path',3)):
        lines+=[key+':','.byte '+','.join(str(bx[k]) for _,bx,_ in ps)]
    lines+=['patlo:','.byte '+','.join('<pat_'+n for n,_,_ in ps),'pathi:','.byte '+','.join('>pat_'+n for n,_,_ in ps)]
    for n,bx,data in ps:
        lines.append('pat_'+n+':')
        for i in range(0,len(data),bx[1]):lines.append('.byte '+','.join(map(str,data[i:i+bx[1]])))
    (ROOT/'src/chapter_art.inc').write_text('\n'.join(lines)+'\n')
    for n,bx,data in ps:print('patch %-6s cols %d-%d rows %d-%d: %d bytes'%(n,bx[0],bx[0]+bx[1]-1,bx[2],bx[2]+bx[3]-1,len(data)))
if __name__=='__main__':main()
