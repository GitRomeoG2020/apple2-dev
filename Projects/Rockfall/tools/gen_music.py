#!/usr/bin/env python3
"""Author the dark two-voice title music -> src/music.inc.

Key: D minor with Phrygian colour (Eb = flat 2). Two 1-bit voices, mixed by the
player in src/rockfall.s (`music`): voice 1 = lead (with vibrato), voice 2 = bass.
Timing unit = one title tick (one music segment, ~12 ms); an eighth note = E ticks.
Each stream is a list of (note index, ticks) byte pairs; index 0 = rest, $FF = jump to
the stream's loop label (the intro plays once, the rest loops seamlessly).
Usage: gen_music.py  (writes ../src/music.inc)"""
import os
CPU=1020484               # Apple II NTSC CPU clock (Hz)
LOOPCYC=63                # cycles per iteration of the two-voice loop
RATE=CPU/LOOPCYC          # iterations per second
SEGN=176                  # iterations per title tick (~= the old WAIT $40)
E=26                      # ticks per eighth note
GAP=2                     # articulation: ticks of silence at the end of each note

def hz(m): return 440*2**((m-69)/12)
def inc(m): return 0 if m is None else round(hz(m)*131072/RATE)   # one toggle per 16-bit carry
N=dict(C=0,Cs=1,D=2,Eb=3,E=4,F=5,Fs=6,G=7,Ab=8,A=9,Bb=10,B=11)
def n(name,octv): return 12*(octv+1)+N[name]

# ---- bass: pulsing low ostinato, 8 eighths per bar: root root oct root | root 5th oct b2/root
def bassbar(root,b2=False):
    pat=[0,0,12,0,0,7,12,1 if b2 else 0]
    return [(root+o,1) for o in pat]
prog=[('D',0),('D',1),('Eb',0),('D',1), ('Bb',0),('G',0),('A',0),('A',1), ('D',0),('Eb',0),('Bb',0),('A',1)]
def broot(nm): r=n(nm,2); return r-12 if r>n('F',2) else r   # keep it low (D2..A1)
bass_loop=sum((bassbar(broot(nm),b2) for nm,b2 in prog),[])
# ---- lead: slow haunting line (note, eighths); None = rest
lead_loop=[(n('D',5),4),(n('C',5),2),(n('A',4),2),   (n('F',4),6),(n('E',4),2),
           (n('Eb',5),4),(n('D',5),2),(n('Bb',4),2), (n('A',4),8),
           (n('F',5),4),(n('D',5),2),(n('Bb',4),2),  (n('G',4),4),(n('Bb',4),2),(n('D',5),2),
           (n('Cs',5),6),(n('E',5),2),               (n('A',4),6),(None,2),
           (n('D',5),2),(n('F',5),2),(n('A',5),4),   (n('G',5),4),(n('F',5),2),(n('Eb',5),2),
           (n('D',5),4),(n('Bb',4),2),(n('F',4),2),  (n('Cs',5),4),(n('A',4),4)]
# ---- doom intro (2 bars, once): long low D with a creeping Eb against it
bass_intro=[(n('D',2),8),(n('D',2),8)]
lead_intro=[(n('D',3),6),(n('Eb',3),2),(n('D',3),4),(None,4)]

def ticks(seq,legato):
    out=[]
    for m,e in seq:
        t=e*E
        if m is None: out.append((None,t))
        elif legato or True: out+= [(m,t-GAP),(None,GAP)]
    return out
def streams():
    S={}
    for v,(intro,loop) in {'lead':(lead_intro,lead_loop),'bass':(bass_intro,bass_loop)}.items():
        S[v]=(ticks(intro,1),ticks(loop,1))
    for i in (0,1):
        a,b=sum(t for _,t in S['lead'][i]),sum(t for _,t in S['bass'][i])
        assert a==b,(i,a,b)
    return S
def notes(S):
    ms=sorted({m for v in S.values() for part in v for m,_ in part if m is not None})
    return [None]+ms
def main():
    S=streams(); NT=notes(S); idx={m:i for i,m in enumerate(NT)}
    L=['; generated by tools/gen_music.py -- do not edit',
       'MSEGN = %d'%SEGN, 'MVIBS = 3   ; vibrato step length (ticks)']
    L.append('minclo: .byte '+','.join('<%d'%inc(m) for m in NT))
    L.append('minchi: .byte '+','.join('>%d'%inc(m) for m in NT))
    for v in ('lead','bass'):
        intro,loop=S[v]
        for lab,part in (('m%s'%v,intro),('m%sl'%v,loop)):
            b=[]
            for m,t in part:
                while t>0:
                    k=min(t,255); b+=[idx[m],k]; t-=k
            if lab.endswith('l'): b.append(255)
            L.append('%s: .byte '%lab+','.join(map(str,b)))
    open(os.path.join(os.path.dirname(__file__),'..','src','music.inc'),'w').write('\n'.join(L)+'\n')
    il=sum(t for _,t in S['lead'][0]); ll=sum(t for _,t in S['lead'][1])
    print('notes %d, intro %d ticks, loop %d ticks (~%.1f s at 12.2 ms/tick)'%(len(NT)-1,il,ll,ll*0.0122))
if __name__=='__main__': main()
