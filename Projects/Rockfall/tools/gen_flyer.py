#!/usr/bin/env python3
"""gen_flyer.py: bonus flyer sprites -> src/flyer.inc.
21x7 px art ('#' = pixel), pre-shifted 0..6 px into 4-byte rows (bit0 = leftmost, palette 0)
for clipped XOR blits.  Sprites: 0 comet moving right, 1 comet moving left (mirrored),
2/3 satellite with its beacon on/off.  Plus a 3x7-byte explosion burst (unshifted)."""
import os
D=os.path.dirname(os.path.abspath(__file__))+'/..'
COMET_R="""
...........#..##.....
.....#..#.##.#####...
#.#..#.##.###########
...#.#.##.###########
#.#..#.##.###########
.....#..#.##.#####...
...........#..##.....
"""
SAT_A="""
.........###.........
#######..#.#..#######
#.#.#.####.####.#.#.#
#######.#####.#######
#.#.#.####.####.#.#.#
#######..#.#..#######
.........#.#.........
"""
SAT_B=SAT_A.replace(".........###.........","..........#..........",1)
BURST="""
..#....#...#....#....
#...##...#...##...#..
..#..#.##.##.#..#...#
.#.##.##..#.##.##.#..
#...#..#.###.#..#..#.
..#...#..#.#...#...#.
.#..#....#...#....#..
"""
art=lambda s:[l for l in s.strip('\n').split('\n')]
def rows_bytes(a,shift,nb):
    out=[]
    for l in a:
        for b in range(nb):
            v=0
            for i in range(7):
                x=b*7+i-shift
                if 0<=x<len(l) and l[x]=='#': v|=1<<i
            out.append(v)
    return out
S=[art(COMET_R),[l[::-1] for l in art(COMET_R)],art(SAT_A),art(SAT_B)]
def sprite(k,shift): return rows_bytes(S[k],shift,4)
BURST_BYTES=rows_bytes(art(BURST),0,3)
def main():
  o=['; generated by tools/gen_flyer.py -- do not edit','FLYW = 4','FLYH = 7']
  for k,a in enumerate(S):
      assert all(len(l)==21 for l in a) and len(a)==7
      for sh in range(7):
          o.append('fly%d_%d: .byte '%(k,sh)+','.join('$%02X'%v for v in rows_bytes(a,sh,4)))
  o.append('flyspr_lo: .byte '+','.join('<fly%d_%d'%(k,s) for k in range(4) for s in list(range(7))+[0]))
  o.append('flyspr_hi: .byte '+','.join('>fly%d_%d'%(k,s) for k in range(4) for s in list(range(7))+[0]))
  o.append('burst: .byte '+','.join('$%02X'%v for v in rows_bytes(art(BURST),0,3)))
  open(D+'/src/flyer.inc','w').write('\n'.join(o)+'\n'); print('flyer.inc: %d sprite bytes + 21 burst'%(4*7*28))

if __name__=='__main__': main()
