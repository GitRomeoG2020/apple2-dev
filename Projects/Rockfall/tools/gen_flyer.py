#!/usr/bin/env python3
"""gen_flyer.py: bonus flyer sprites -> src/flyer.inc.
21x7 px art ('#' = pixel), pre-shifted 0..6 px into 4-byte rows (bit0 = leftmost, palette 0)
for clipped XOR blits.  Sprites: 0 comet moving right, 1 comet moving left (mirrored),
2/3 satellite with its beacon on/off.  Plus a 3x7-byte explosion burst (unshifted)."""
import os
D=os.path.dirname(os.path.abspath(__file__))+'/..'
COMET_R="""
...........#..##.....
.....#..#.##.#####...
#.#..#.##.###########
...#.#.##.###########
#.#..#.##.###########
.....#..#.##.#####...
...........#..##.....
"""
SAT_A="""
.........###.........
#######..#.#..#######
#.#.#.####.####.#.#.#
#######.#####.#######
#.#.#.####.####.#.#.#
#######..#.#..#######
.........#.#.........
"""
SAT_B=SAT_A.replace(".........###.........","..........#..........",1)
SHIP=["......XX......","......XX......",".....XXXX.....",".....XXXX.....","...XXXXXXXX...",".XXXXXXXXXXXX.","XXXXXXXXXXXXXX","XX..XX..XX..XX"]   # = gen_sprites.js ship
def _shield():
    """shielded ship: the ship at x 4..17 / rows 2..9 inside a dotted bubble (rows 0..9, 21 px)"""
    g=[['.']*21 for _ in range(10)]
    for y,r in enumerate(SHIP):
        for x,c in enumerate(r):
            if c=='X': g[y+2][x+4]='#'
    for x in range(5,16,2): g[0][x]='#'
    for x in (3,17): g[1][x]='#'
    for y in range(2,10,2): g[y][1]='#'; g[y][19]='#'
    return '\n'.join(''.join(r) for r in g)
SHIELD=_shield()
BURST="""
..#....#...#....#....
#...##...#...##...#..
..#..#.##.##.#..#...#
.#.##.##..#.##.##.#..
#...#..#.###.#..#..#.
..#...#..#.#...#...#.
.#..#....#...#....#..
"""
art=lambda s:[l for l in s.strip('\n').split('\n')]
def rows_bytes(a,shift,nb):
    out=[]
    for l in a:
        for b in range(nb):
            v=0
            for i in range(7):
                x=b*7+i-shift
                if 0<=x<len(l) and l[x]=='#': v|=1<<i
            out.append(v)
    return out
S=[art(COMET_R),[l[::-1] for l in art(COMET_R)],art(SAT_A),art(SAT_B),art(SHIELD)]   # 4 = shielded ship (10 rows)
FLYHS=[len(a) for a in S]
def sprite(k,shift): return rows_bytes(S[k],shift,4)
BURST_BYTES=rows_bytes(art(BURST),0,3)
def main():
  o=['; generated by tools/gen_flyer.py -- do not edit','FLYW = 4','FLYH = 7']
  for k,a in enumerate(S):
      assert all(len(l)==21 for l in a)
      for sh in range(7):
          o.append('fly%d_%d: .byte '%(k,sh)+','.join('$%02X'%v for v in rows_bytes(a,sh,4)))
  o.append('flyspr_lo: .byte '+','.join('<fly%d_%d'%(k,s) for k in range(len(S)) for s in list(range(7))+[0]))
  o.append('flyspr_hi: .byte '+','.join('>fly%d_%d'%(k,s) for k in range(len(S)) for s in list(range(7))+[0]))
  o.append('flyh: .byte '+','.join(str(h) for h in FLYHS))
  o.append('burst: .byte '+','.join('$%02X'%v for v in rows_bytes(art(BURST),0,3)))
  open(D+'/src/flyer.inc','w').write('\n'.join(o)+'\n'); print('flyer.inc: %d sprite bytes + 21 burst'%(4*7*28))

if __name__=='__main__': main()
