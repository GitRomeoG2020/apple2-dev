#!/usr/bin/env python3
"""Boss meteor sprite -> src/boss.inc: 5 bytes (35 px) x 24 rows, cratered disc with a jagged rim."""
import math
W,H=35,24
cx,cy=17,11.5
crat=[(10,7,3.2),(23,14,4.0),(13,17,2.4),(25,6,2.0),(18,11,1.6)]
rows=[]
for y in range(H):
    bits=[]
    for x in range(W):
        dx=(x-cx)/17.0; dy=(y-cy)/11.5
        a=math.atan2(dy,dx); r=1.0-0.08*math.sin(5*a)-0.05*math.sin(11*a+1)
        on=dx*dx+dy*dy<=r*r
        for (ox,oy,rr) in crat:
            d=math.hypot((x-ox)/1.6,y-oy)
            if rr-0.9<=d<=rr: on=False                   # crater ring
            elif d<rr-0.9 and (x+y)%2: on=False          # dithered crater floor
        bits.append(1 if on else 0)
    rows.append([sum(bits[b*7+i]<<i for i in range(7)) for b in range(5)])
o=['; generated by tools/gen_boss.py','BOSS_W = 5','BOSS_H = %d'%H,'','boss_spr:']
o+=['        .byte '+','.join('$%02X'%v for v in r)+'   ; row %d'%i for i,r in enumerate(rows)]
open(__file__.rsplit('/',2)[0]+'/src/boss.inc','w').write('\n'.join(o)+'\n')
for r in rows: print(''.join('#' if (r[i//7]>>(i%7))&1 else '.' for i in range(W)))
