const crack=[[10,0],[10,1],[9,2],[9,3],[10,4],[11,5],[11,6],[10,7],[9,8],[9,9],[10,10],[11,11],[11,12],[10,13],[8,4],[7,5],[12,8],[13,9]];
const cracked=boulder.map(r=>[...r]); crack.forEach(([x,y])=>{cracked[y][x]='.';});
// power-up capsules: rounded box with the HUD icon inside (3x5 font doubled); frame 1 = glowing (filled)
const ICON={shield:['111','111','111','111','010'],cool:['101','010','111','010','101'],spread:['101','111','010','010','010'],oneup:['010','010','111','111','101']};
function capsule(ic,glow){const a=[];for(let y=0;y<9;y++){let r='';for(let x=0;x<14;x++){
  const edge=(y==0||y==8)?(x>=2&&x<=11):(x==0||x==13||((y==1||y==7)&&(x==1||x==12)));
  const inBox=y>=1&&y<=7&&x>=1&&x<=12&&!((y==1||y==7)&&(x==1||x==12));
  let on=edge; const gx=x-4,gy=y-2;
  const g=gx>=0&&gx<6&&gy>=0&&gy<5&&ICON[ic][gy][gx>>1]==='1';
  if(glow) on=on||(inBox&&!g); else on=on||g;
  r+=on?'X':'.';}a.push(r);}return mk(a);}
let t='; generated by tools/gen_sprites.js (a2sprite encoder) - do not edit by hand\n        .segment "RODATA"\n';
t+=A.exportSpriteAsm(ship,'ship',{shifts:true})+'\n'+A.exportSpriteAsm(rock,'rock',{})+'\n'+A.exportSpriteAsm(pebble,'pebble',{})+'\n'+A.exportSpriteAsm(mk(boulder,3),'boulder',{})+'\n'+A.exportSpriteAsm(mk(cracked.map(r=>r.join('')),3),'boulder_cracked',{});
['shield','cool','spread','oneup'].forEach(ic=>{[0,1].forEach(g=>{t+='\n'+A.exportSpriteAsm(capsule(ic,g),'cap_'+ic+g,{});});});
fs.writeFileSync(__dirname+'/../src/sprites.s',t);
