// Regenerates src/sprites.s from ASCII art using the a2sprite encoder (a2enc.js).
// Run: node tools/gen_sprites.js   (only needed if you change the art)
const A=require('./a2enc.js'),fs=require('fs');
function mk(art){const s=A.newSprite(2,art.length);art.forEach((r,y)=>[...r].forEach((c,x)=>s.px[y][x]=c==='X'?1:0));return s;}
const ship=mk([
"......XX......",
"......XX......",
".....XXXX.....",
".....XXXX.....",
"...XXXXXXXX...",
".XXXXXXXXXXXX.",
"XXXXXXXXXXXXXX",
"XX..XX..XX..XX"]);
const rock=mk([
"....XXXXXX....",
"..XXXXXXXXXX..",
".XXXX.XXXXXXX.",
"XXXXXXXX.XXXXX",
"XXX.XXXXXXXXXX",
".XXXXXXXX.XXX.",
"..XXXXXXXXXX..",
"....XXXXXX...."]);
let t='; generated by tools/gen_sprites.js (a2sprite encoder) - do not edit by hand\n        .segment "RODATA"\n';
t+=A.exportSpriteAsm(ship,'ship',{shifts:true})+'\n'+A.exportSpriteAsm(rock,'rock',{});
fs.writeFileSync(__dirname+'/../src/sprites.s',t);
